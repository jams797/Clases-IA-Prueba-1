const assert = require('assert').strict;
const auth = require('../auth.js');
const registration = require('../registro-service.js');
globalThis.crypto = require('crypto').webcrypto;

(async () => {
  let time = Date.now();
  const values = new Map();
  const storage = { getItem: key => values.get(key) || null, setItem: (key, value) => values.set(key, value), removeItem: key => values.delete(key) };
  const service = registration.create(storage, auth, globalThis.crypto, () => time);
  const data = { name: 'Ana Pérez', email: 'ana@example.com', phone: '099 123 4567', address: 'Calle 1, Quito', terms: true };
  assert.equal(Object.keys(registration.validate({ name: '', email: 'mal', phone: '123', address: '', terms: false })).length, 5);
  assert.equal(registration.normalizePhone('+593 99 123 4567'), '991234567');
  assert.ok(service.start({ ...data, email: 'demo@jose.com' }).errors.email);
  await assert.rejects(service.save('Nueva2026!', 'Nueva2026!'), /Verifica/);
  let draft = service.start(data).draft;
  assert.equal(draft.data.phone, '991234567');
  assert.throws(() => service.verify('12'), /6 dígitos/);
  assert.throws(() => service.resend(), /Espera/);
  const wrong = draft.code === '111111' ? '222222' : '111111';
  for (let i = 0; i < 5; i++) assert.throws(() => service.verify(wrong), /incorrecto|5 intentos/);
  assert.throws(() => service.verify(draft.code), /5 intentos/);
  time += registration.WAIT;
  const oldCode = draft.code;
  draft = service.resend();
  assert.notEqual(draft.code, oldCode);
  assert.throws(() => service.verify(oldCode), /incorrecto/);
  time += registration.TTL;
  assert.throws(() => service.verify(draft.code), /venció/);
  draft = service.resend();
  service.verify(draft.code);
  await assert.rejects(service.save('abc', 'abc'), /requisitos/);
  await assert.rejects(service.save('Nueva2026!', 'Otra2026!'), /coinciden/);
  // Cambiar datos invalida la verificación anterior.
  draft = service.start({ ...data, phone: '0987654321' }).draft;
  assert.equal(draft.verified, false);
  await assert.rejects(service.save('Nueva2026!', 'Nueva2026!'), /Verifica/);
  service.verify(draft.code);
  await service.save('Nueva2026!', 'Nueva2026!');
  assert.equal(service.read(), null);
  assert.equal(storage.getItem(auth.PREFILL_KEY), 'ana@example.com');
  assert.equal(await auth.verifyCredentials(' ANA@example.com ', 'Nueva2026!', storage), true);
  assert.equal(await auth.verifyCredentials('ana@example.com', 'Erronea2026!', storage), false);
  assert.ok(!JSON.stringify([...values]).includes('Nueva2026!'));
  assert.ok(!JSON.stringify([...values]).includes('Calle 1'));
  assert.ok(service.start(data).errors.email);
  storage.setItem(auth.SESSION_KEY, JSON.stringify({ email: 'ana@example.com', expiresAt: Date.now() + 10000 }));
  assert.equal(auth.readSession(storage).email, 'ana@example.com');
  storage.removeItem(auth.SESSION_KEY);
  assert.equal(auth.readSession(storage), null);
  storage.setItem(registration.KEY, '{invalid');
  assert.equal(service.read(), null);
  console.log('OK: datos, duplicados, OTP incompleto, intentos, reenvío, vencimiento, cambios de datos, reglas de contraseña, alta, hash, login y cierre de sesión');
})().catch(error => { console.error(error); process.exitCode = 1; });
