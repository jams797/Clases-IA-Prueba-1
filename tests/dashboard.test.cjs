const assert = require('assert').strict;
const dashboard = require('../dashboard-data.js');
const values = new Map();
const storage = { getItem: key => values.get(key) || null, setItem: (key, value) => values.set(key, value) };
const first = dashboard.create(storage, 'ana@example.com');
assert.equal(first.get().products[0].balance, 245030);
assert.equal(dashboard.parseAmount('12,50'), 1250);
assert.equal(dashboard.parseAmount('0.01'), 1);
for (const invalid of ['0', '-1', '1.234', '1,000.00', 'NaN', '1e3', '']) assert.equal(dashboard.parseAmount(invalid), null);
assert.ok(first.execute('transferir', '', '10').errors.destination);
assert.ok(first.execute('transferir', 'Carlos Pérez', '9999').errors.amount);
assert.ok(first.execute('recargas', '123', '10').errors.destination);
assert.equal(first.get().products[0].balance, 245030);
const operation = first.execute('transferir', 'Carlos Pérez', '10,25');
assert.equal(operation.movement.amount, -1025);
assert.equal(first.get().products[0].balance, 244005);
assert.equal(first.get().movements[0].detail, 'Carlos Pérez');
assert.equal(dashboard.create(storage, 'ana@example.com').get().products[0].balance, 244005);
assert.equal(dashboard.create(storage, 'otro@example.com').get().products[0].balance, 245030);
first.preferences({ hidden: true, shortcuts: ['qr', 'movimientos'], notificationsRead: true });
assert.equal(first.get().hidden, true);
assert.deepEqual(first.get().shortcuts, ['qr', 'movimientos']);
const copy = first.get(); copy.products[0].balance = 0;
assert.equal(first.get().products[0].balance, 244005);
let fail = false;
const faultyStorage = { getItem() { return null; }, setItem() { if (fail) throw Error('blocked'); } };
const faulty = dashboard.create(faultyStorage, 'test@example.com');
fail = true;
assert.throws(() => faulty.execute('pagos', 'Energía eléctrica', '10'), /blocked/);
assert.equal(faulty.get().products[0].balance, 245030);
assert.equal(faulty.get().movements.length, 6);
assert.throws(() => faulty.preferences({ hidden: true }), /blocked/);
assert.equal(faulty.get().hidden, false);
values.set('jose.dashboard.corrupt@example.com', '{bad json');
assert.equal(dashboard.create(storage, 'corrupt@example.com').get().products.length, 3);
console.log('OK: importes en centavos, validaciones, simulación, saldo, movimientos, preferencias, aislamiento por cuenta y escritura fallida sin cambios parciales');
